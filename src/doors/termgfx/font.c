static const uint8_t *glyph_of(char ch)
{
	int c = (unsigned char)ch;

	if (c >= 'a' && c <= 'z')
		c -= 32;                       /* fold, rather than blank */
	if (c < FIRST_CH || c > LAST_CH)
		return NULL;
	return glyph[c - FIRST_CH];
}

static void blot(uint8_t *fb, int fbw, int fbh, int x, int y, int scale,
                 uint8_t color)
{
	int i, j;

	for (j = 0; j < scale; j++) {
		int py = y + j;

		if (py < 0 || py >= fbh)
			continue;
		for (i = 0; i < scale; i++) {
			int px = x + i;

			/* Clipped per pixel: a caption running off the edge
			 * should lose its tail, not the door. */
			if (px < 0 || px >= fbw)
				continue;
			fb[(size_t)py * fbw + px] = color;
		}
	}
}

static void one(uint8_t *fb, int fbw, int fbh, int x, int y,
                const uint8_t *g, int scale, uint8_t color)
{
	int r, c;

	for (r = 0; r < TERMGFX_FONT_H; r++)
		for (c = 0; c < TERMGFX_FONT_W; c++)
			if (g[r] & (0x10 >> c))
				blot(fb, fbw, fbh, x + c * scale,
				     y + r * scale, scale, color);
}

void termgfx_font_glyph(uint8_t *fb, int fbw, int fbh, int x, int y,
                        char ch, int scale, uint8_t color, int shadow)
{
	const uint8_t *g = glyph_of(ch);

	if (fb == NULL || g == NULL || scale < 1)
		return;
	/* Shadow first, whole, then the glyph over it. Drawing them together
	 * per pixel would let one glyph's shadow fall on top of the last
	 * one's face where they overlap. */
	if (shadow >= 0)
		one(fb, fbw, fbh, x + scale, y + scale, g, scale,
		    (uint8_t)shadow);
	one(fb, fbw, fbh, x, y, g, scale, color);
}

int termgfx_font_width(const char *s, int scale)
{
	int n = 0;

	if (s == NULL || scale < 1)
		return 0;
	for (; *s != '\0'; s++)
		n++;
	if (n == 0)
		return 0;
	return n * TERMGFX_FONT_W * scale + (n - 1) * TERMGFX_FONT_GAP * scale;
}

int termgfx_font_text(uint8_t *fb, int fbw, int fbh, int x, int y,
                      const char *s, int scale, uint8_t color, int shadow)
{
	int at = x;

	if (fb == NULL || s == NULL || scale < 1)
		return 0;
	for (; *s != '\0'; s++) {
		termgfx_font_glyph(fb, fbw, fbh, at, y, *s, scale, color,
		                   shadow);
		at += (TERMGFX_FONT_W + TERMGFX_FONT_GAP) * scale;
	}
	return (at > x) ? (at - x - TERMGFX_FONT_GAP * scale) : 0;
}
