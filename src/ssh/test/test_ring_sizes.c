static uint64_t checks;
static uint64_t failed;

static void
check(dssh_ring_size capacity, dssh_ring_size index, dssh_ring_size count,
    uint64_t expected)
{
	dssh_ring_size actual = dssh_ring_advance(index, count, capacity);
	/* The exhaustive domain and fixed table together contain fewer than 2^24
	 * checks, so neither counter can overflow. */
	checks++;
	if (actual != expected) {
		if (failed == 0) {
			uintmax_t reported_capacity = capacity;
			uintmax_t reported_index = index;
			uintmax_t reported_count = count;
			uintmax_t reported_actual = actual;
			fprintf(stderr, "ring capacity=%" PRIuMAX " index=%" PRIuMAX
			    " count=%" PRIuMAX " actual=%" PRIuMAX " expected=%" PRIu64 "\n",
			    reported_capacity, reported_index, reported_count, reported_actual, expected);
		}
		failed++;
	}
}

int
main(void)
{
	/* All valid index/count combinations at every positive 8-bit capacity.
	 * Both the loop arithmetic and independent sum fit uint32_t, even on a
	 * conforming 16-bit int host. */
	for (uint32_t capacity = 1; capacity <= UINT8_MAX; capacity++) {
		for (uint32_t index = 0; index < capacity; index++) {
			for (uint32_t count = 0; count <= capacity; count++) {
				dssh_ring_size safe_capacity = (dssh_ring_size)capacity;
				dssh_ring_size safe_index = (dssh_ring_size)index;
				dssh_ring_size safe_count = (dssh_ring_size)count;
				uint64_t expected = (index + count) % capacity;
				check(safe_capacity, safe_index, safe_count, expected);
			}
		}
	}
	uintmax_t maximum = DSSH_RING_SIZE_LIMIT;
	for (size_t i = 0; i < sizeof(answers) / sizeof(answers[0]); i++) {
		if (answers[i].capacity > maximum)
			continue;
		/* Every row is in the helper's domain. The capacity check bounds all
		 * three conversions before passing them to the selected model. */
		dssh_ring_size capacity = (dssh_ring_size)answers[i].capacity;
		dssh_ring_size index = (dssh_ring_size)answers[i].index;
		dssh_ring_size count = (dssh_ring_size)answers[i].count;
		check(capacity, index, count, answers[i].expected);
	}
	unsigned width = (unsigned)(sizeof(dssh_ring_size) * CHAR_BIT);
	int printed = printf("ring_sizes model=%s width=%u checks=%" PRIu64 " failed=%" PRIu64 "\n",
	    DSSH_RING_MODEL_NAME, width, checks, failed);
	return failed == 0 && checks != 0 && printed >= 0 ? 0 : 1;
}
