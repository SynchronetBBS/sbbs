#!/usr/bin/env python3
"""Public test constants from RFC 7748, with an independent integer oracle.

This variable-time Python code is only a test-vector generator. It is never
linked into DeuceSSH and must not be used to process private application keys.
"""
import pathlib
import sys

P = 2**255 - 19
PRIMITIVE = [
    ('a546e36bf0527c9d3b16154b82465edd62144c0ac1fc5a18506a2244ba449ac4',
     'e6db6867583030db3594c1a424b15f7c726624ec26b3353b10a903a6d0ab1c4c',
     'c3da55379de9c6908e94ea4df28d084f32eccf03491c71f754b4075577a28552'),
    ('4b66e9d4d1b4673c5ad22691957d6af5c11b6421e0ea01d42ca4169e7918ba0d',
     'e5210f12786811d3f4b7959d0538ae2c31dbe7106fc03c3efc4cd549c715a493',
     '95cbde9476e8907d7aade45cb4b873f88b595a68799fa152e6f8f7647aac7957'),
]
PRIVATE = [
    '77076d0a7318a57d3c16c17251b26645df4c2f87ebc0992ab177fba51db92c2a',
    '5dab087e624a8a4b79e17f8b83800ee66f3bb1292618b6fd1c2f8b27ff88e0eb',
]
PUBLIC = [
    '8520f0098930a754748b7ddcb43ef75a0dbf3a0d26381af4eba4a98eaa9b4e6a',
    'de9edb7d7b7dc1b4d35b61c2ece435373f8343c85b78674dadfc7e146f882b4f',
]
SHARED = '4a5d9d5ba4ce2de1728e3bf480350f25e07e21c947d19e3376f09b3c1e161742'
ITERATED = [
    '422c8e7a6227d7bca1350b3e2bb7279f7897b87bb6854b783c60e80311ae3079',
    '684cf59ba83309552800ef566f2f4d3c1c3887c49360e3875f2eb94d99532c51',
    '7c3911e0ab2586fd864497297e575e6f3bc601c0883c30df5f4dd2d24f665424',
]


def multiply(scalar, coordinate):
    k = (int.from_bytes(scalar, 'little') & (2**255 - 8)) | 2**254
    u = (int.from_bytes(coordinate, 'little') & (2**255 - 1)) % P
    x, z, other_x, other_z, previous = 1, 0, u, 1, 0
    for bit_index in range(254, -1, -1):
        bit = (k >> bit_index) & 1
        if bit != previous:
            x, other_x = other_x, x
            z, other_z = other_z, z
        previous = bit
        plus, minus = (x + z) % P, (x - z) % P
        plus_squared, minus_squared = plus**2 % P, minus**2 % P
        difference = (plus_squared - minus_squared) % P
        cross_a = (other_x - other_z) * plus % P
        cross_b = (other_x + other_z) * minus % P
        other_x = (cross_a + cross_b)**2 % P
        other_z = u * (cross_a - cross_b)**2 % P
        x = plus_squared * minus_squared % P
        z = difference * (plus_squared + 121665 * difference) % P
    if previous:
        x, other_x = other_x, x
        z, other_z = other_z, z
    return (x * pow(z, P - 2, P) % P).to_bytes(32, 'little')


def render():
    base = bytes([9]) + bytes(31)
    for scalar, coordinate, result in PRIMITIVE:
        assert multiply(bytes.fromhex(scalar), bytes.fromhex(coordinate)).hex() == result
    for party in range(2):
        key = bytes.fromhex(PRIVATE[party])
        assert multiply(key, base).hex() == PUBLIC[party]
        assert multiply(key, bytes.fromhex(PUBLIC[1 - party])).hex() == SHARED
    scalar = coordinate = base
    for iteration in range(1, 1001):
        scalar, coordinate = multiply(scalar, coordinate), scalar
        if iteration in (1, 1000):
            assert scalar.hex() == ITERATED[0 if iteration == 1 else 1]
    lines = [
        '/* Generated by x25519_reference.py; RFC 7748 sections 5.2 and 6.1.',
        ' * Small-coordinate answers use its independent public-data oracle. */',
        '#ifndef DSSH_TEST_X25519_VECTORS_H', '#define DSSH_TEST_X25519_VECTORS_H', '',
        'static const char *const x25519_primitive[2][3] = {',
    ]
    for vector in PRIMITIVE:
        lines.append('\t{')
        lines.extend(f'\t\t"{value}",' for value in vector)
        lines.append('\t},')
    lines.append('};')
    for name, values in [('private', PRIVATE), ('public', PUBLIC), ('iterated', ITERATED)]:
        lines.append(f'static const char *const x25519_{name}[{len(values)}] = {{')
        lines.extend(f'\t"{value}",' for value in values)
        lines.append('};')
    lines.append(f'static const char x25519_shared[] = "{SHARED}";')
    lines.append('static const char *const x25519_small[2][19] = {')
    for scalar in PRIVATE:
        lines.append('\t{')
        for coordinate in range(19):
            answer = multiply(bytes.fromhex(scalar), coordinate.to_bytes(32, 'little'))
            lines.append(f'\t\t"{answer.hex()}",')
        lines.append('\t},')
    lines.extend(['};', '#endif', ''])
    return '\n'.join(lines)


if __name__ == '__main__':
    path = pathlib.Path(__file__).with_name('x25519_vectors.h')
    expected = render()
    if sys.argv[1:] == ['--check']:
        assert path.read_text() == expected
        print('X25519 reference: published primitive/agreement/1/1000 answers and generated header verified')
    elif not sys.argv[1:]:
        path.write_text(expected)
    else:
        raise SystemExit('usage: x25519_reference.py [--check]')
