struct key_material_producer {
	dssh_kex_handler handler;
	struct dssh_result_lease inner;
	/* Built-in DH groups are at most 1024 bytes; hybrid hashes at most 64.
	 * This is a test producer's fixed, known capacity, not a library limit. */
	uint8_t storage[1032];
	size_t prefix;
	bool client;
	bool valid;
	bool live;
	unsigned calls;
	unsigned releases;
};
static struct key_material_producer *key_material_producer;

static void
key_material_release(void *owner)
{
	struct key_material_producer *p = owner;
	p->valid = p->valid && p->live;
	dssh_result_release(&p->inner);
	dssh_cleanse(p->storage, sizeof(p->storage));
	p->live = false;
	p->releases++;
}

static int
key_material_handler(const struct dssh_kex_context *ctx, struct dssh_kex_result *out)
{
	struct key_material_producer *p = key_material_producer;
	int ret = p->handler(ctx, out);
	if (ret != 0 || ctx->client != p->client)
		return ret;
	if (p->live || out->shared_secret.len > sizeof(p->storage) - p->prefix) {
		p->valid = false;
		return DSSH_ERROR_INVALID;
	}
	for (size_t i = 0; i < sizeof(p->storage); i++)
		p->valid = p->valid && p->storage[i] == 0;
	memcpy(p->storage + p->prefix, out->shared_secret.data, out->shared_secret.len);
	p->inner = out->lease;
	out->shared_secret = (struct dssh_bytes){p->storage, out->shared_secret.len + p->prefix};
	out->lease = (struct dssh_result_lease){key_material_release, p};
	p->live = true;
	p->calls++;
	return 0;
}

static int
key_material_register_producer(void)
{
	if (gconf.kex_head == NULL)
		return DSSH_ERROR_INIT;
	key_material_producer->prefix = (gconf.kex_head->flags & DSSH_KEX_FLAG_K_ENCODING_STRING) != 0 ? 0 : 3;
	key_material_producer->handler = gconf.kex_head->handler;
	gconf.kex_head->handler = key_material_handler;
	return 0;
}

static bool
key_material_roundtrip(struct handshake_ctx *ctx)
{
	const uint8_t message[] = {SSH_MSG_CHANNEL_DATA, 0, 0, 0, 0, 0, 0, 0, 1, 0xa5};
	uint8_t type;
	uint8_t *payload;
	size_t length;
	int ret = send_packet(ctx->client, message, sizeof(message), NULL);
	if (ret == 0)
		ret = recv_packet(ctx->server, &type, &payload, &length);
	if (ret != 0 || type != message[0] || length != sizeof(message)
	    || memcmp(payload, message, length) != 0)
		return false;
	ret = send_packet(ctx->server, message, sizeof(message), NULL);
	if (ret == 0)
		ret = recv_packet(ctx->client, &type, &payload, &length);
	return ret == 0 && type == message[0] && length == sizeof(message)
	    && memcmp(payload, message, length) == 0;
}

static int
test_key_material_paired_producer(void)
{
	unsigned passed = 0;
	for (unsigned role = 0; role < 2; role++) {
		struct key_material_producer producer = {.client = role == 0, .valid = true};
		key_material_producer = &producer;
		int (*previous)(void) = extra_algorithm_registration;
		extra_algorithm_registration = key_material_register_producer;
		struct handshake_ctx ctx;
		int ret = handshake_setup(&ctx);
		extra_algorithm_registration = previous;
		bool valid = ret == 0;
		struct rekey_control_probe watch = {.pair = &ctx};
		atomic_init(&watch.finished, false);
		atomic_init(&watch.timed_out, false);
		thrd_t watchdog;
		bool watched = valid && thrd_create(&watchdog, rekey_control_watchdog, &watch) == thrd_success;
		valid = valid && watched && key_material_roundtrip(&ctx);
		if (valid) {
			struct compression_sender client = {.pair = &ctx, .sess = ctx.client, .do_rekey = true, .result = -1};
			struct compression_sender server = {.pair = &ctx, .sess = ctx.server, .do_rekey = true, .result = -1};
			thrd_t ct, st;
			bool cc = thrd_create(&ct, compression_sender_thread, &client) == thrd_success;
			bool sc = cc && thrd_create(&st, compression_sender_thread, &server) == thrd_success;
			if (!sc) {
				dssh_session_terminate(ctx.client);
				dssh_session_terminate(ctx.server);
				mock_io_close_c2s(&ctx.io);
				mock_io_close_s2c(&ctx.io);
			}
			if (cc && thrd_join(ct, NULL) != thrd_success)
				abort();
			if (sc && thrd_join(st, NULL) != thrd_success)
				abort();
			valid = cc && sc && client.result == 0 && server.result == 0 && key_material_roundtrip(&ctx);
		}
		atomic_store(&watch.finished, true);
		if (watched && thrd_join(watchdog, NULL) != thrd_success)
			abort();
		valid = valid && !atomic_load(&watch.timed_out) && producer.valid && !producer.live
		    && producer.calls == 2 && producer.releases == 2;
		handshake_cleanup(&ctx);
		key_material_producer = NULL;
		if (valid)
			passed++;
	}
	printf("key material peers: %u/2 producer roles, initial/rekey, bounded reused storage verified\n", passed);
	ASSERT_EQ_U(passed, 2);
	return TEST_PASS;
}

struct key_material_zero_module {
	atomic_uint inits;
	atomic_uint cleanups;
	atomic_bool valid;
};
static struct key_material_zero_module *key_material_zero_module;

static int
key_material_zero_init(const uint8_t *key, const uint8_t *iv, bool encrypt, dssh_enc_ctx **out)
{
	(void)encrypt;
	if (key == NULL || iv == NULL)
		atomic_store(&key_material_zero_module->valid, false);
	atomic_fetch_add(&key_material_zero_module->inits, 1);
	*out = NULL;
	return 0;
}

static int
key_material_zero_crypt(uint8_t *buf, size_t length, dssh_enc_ctx *ctx)
{
	(void)buf;
	(void)length;
	if (ctx != NULL)
		atomic_store(&key_material_zero_module->valid, false);
	return 0;
}

static void
key_material_zero_cleanup(dssh_enc_ctx *ctx)
{
	if (ctx != NULL)
		atomic_store(&key_material_zero_module->valid, false);
	atomic_fetch_add(&key_material_zero_module->cleanups, 1);
}

static int
key_material_register_zero(void)
{
	dssh_enc module = calloc(1, sizeof(*module) + sizeof("key-zero"));
	if (module == NULL)
		return DSSH_ERROR_ALLOC;
	module->init = key_material_zero_init;
	module->encrypt = key_material_zero_crypt;
	module->decrypt = key_material_zero_crypt;
	module->cleanup = key_material_zero_cleanup;
	module->bytes_per_key = UINT64_MAX;
	memcpy(module->name, "key-zero", sizeof("key-zero"));
	int ret = dssh_transport_register_enc(module);
	if (ret < 0)
		free(module);
	return ret;
}

static int
test_key_material_zero_module(void)
{
	struct key_material_zero_module probe;
	atomic_init(&probe.inits, 0);
	atomic_init(&probe.cleanups, 0);
	atomic_init(&probe.valid, true);
	key_material_zero_module = &probe;
	int (*previous)(void) = extra_algorithm_registration;
	extra_algorithm_registration = key_material_register_zero;
	/* A zero-sized standard allocation may return NULL. Exercise that permitted
	 * result explicitly, rather than depending on the host allocator's choice. */
	dssh_test_malloc_fail_size(0);
	struct handshake_ctx ctx;
	int ret = handshake_setup_filtered(&ctx, false, NULL, "key-zero", NULL);
	extra_algorithm_registration = previous;
	bool valid = ret == 0 && key_material_roundtrip(&ctx);
	bool zero_allocation = dssh_test_malloc_size_failed();
	dssh_test_alloc_reset();
	handshake_cleanup(&ctx);
	valid = valid && !zero_allocation && atomic_load(&probe.valid)
	    && atomic_load(&probe.inits) == 4 && atomic_load(&probe.cleanups) == 4;
	key_material_zero_module = NULL;
	printf("zero-key/IV module: handshake=%d zero-allocation=%u inits=%u cleanups=%u\n",
	    ret, zero_allocation ? 1U : 0U, atomic_load(&probe.inits), atomic_load(&probe.cleanups));
	ASSERT_TRUE(valid);
	return TEST_PASS;
}

static int
key_material_register_hash_changes(void)
{
	bool curve = false;
	bool hybrid = false;
	for (dssh_kex method = gconf.kex_head; method != NULL; method = method->next) {
		curve = curve || strcmp(method->name, "curve25519-sha256") == 0;
		hybrid = hybrid || strcmp(method->name, "sntrup761x25519-sha512") == 0;
	}
	int ret = curve ? 0 : dssh_register_curve25519_sha256();
	if (ret == 0 && !hybrid)
		ret = dssh_register_sntrup761x25519_sha512();
	return ret;
}

static int
test_key_material_hash_changes(void)
{
	int (*previous)(void) = extra_algorithm_registration;
	extra_algorithm_registration = key_material_register_hash_changes;
	struct handshake_ctx ctx;
	int ret = handshake_setup(&ctx);
	extra_algorithm_registration = previous;
	bool valid = ret == 0;
	const char *initial = valid ? ctx.client->trans.kex_selected->name : NULL;
	size_t sid_size = valid ? ctx.client->trans.session_id_sz : 0;
	uint8_t sid[64];
	if (valid) {
		valid = (sid_size == 32 || sid_size == 64)
		    && ctx.server->trans.session_id_sz == sid_size;
		if (valid)
			memcpy(sid, ctx.client->trans.session_id, sid_size);
	}
	struct rekey_control_probe watch = {.pair = &ctx};
	atomic_init(&watch.finished, false);
	atomic_init(&watch.timed_out, false);
	thrd_t watchdog;
	bool watched = valid && thrd_create(&watchdog, rekey_control_watchdog, &watch) == thrd_success;
	valid = valid && watched && key_material_roundtrip(&ctx);
	unsigned transitions = 0;
	for (unsigned round = 0; round < 2 && valid; round++) {
		const char *method = round == 1 ? initial : (sid_size == 64
		    ? "curve25519-sha256" : "sntrup761x25519-sha512");
		valid = dssh_session_set_kex_filter(ctx.client, &method, 1) == 0
		    && dssh_session_set_kex_filter(ctx.server, &method, 1) == 0
		    && compression_rekey_pair(&ctx);
		if (valid) {
			bool sha512 = strcmp(method, "sntrup761x25519-sha512") == 0
			    || strcmp(method, "diffie-hellman-group16-sha512") == 0;
			const char *expected_hash = sha512 ? "SHA-512" : "SHA-256";
			valid = strcmp(ctx.client->trans.kex_selected->name, method) == 0
			    && strcmp(ctx.server->trans.kex_selected->name, method) == 0
			    && strcmp(ctx.client->trans.kex_selected->hash_name, expected_hash) == 0
			    && strcmp(ctx.server->trans.kex_selected->hash_name, expected_hash) == 0
			    && ctx.client->trans.session_id_sz == sid_size && ctx.server->trans.session_id_sz == sid_size
			    && memcmp(ctx.client->trans.session_id, sid, sid_size) == 0
			    && memcmp(ctx.server->trans.session_id, sid, sid_size) == 0
			    && ctx.client->trans.kex_result.lease.release == NULL
			    && ctx.server->trans.kex_result.lease.release == NULL
			    && key_material_roundtrip(&ctx);
		}
		if (valid)
			transitions++;
	}
	atomic_store(&watch.finished, true);
	if (watched && thrd_join(watchdog, NULL) != thrd_success)
		abort();
	valid = valid && !atomic_load(&watch.timed_out) && transitions == 2;
	handshake_cleanup(&ctx);
	printf("key material hash changes: %u/2 method transitions, original %zu-byte session ID retained\n",
	    transitions, sid_size);
	ASSERT_TRUE(valid);
	return TEST_PASS;
}
