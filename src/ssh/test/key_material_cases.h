static int
test_key_material_encoding(void)
{
	static const struct {
		uint8_t raw[5];
		size_t length;
		uint8_t integer[9];
		size_t integer_length;
		uint8_t string[9];
		size_t string_length;
	} cases[] = {
		{{0}, 0, {0, 0, 0, 0}, 4, {0, 0, 0, 0}, 4},
		{{0, 0, 0}, 3, {0, 0, 0, 0}, 4, {0, 0, 0, 3, 0, 0, 0}, 7},
		{{0, 0, 0x7f}, 3, {0, 0, 0, 1, 0x7f}, 5, {0, 0, 0, 3, 0, 0, 0x7f}, 7},
		{{0, 0, 0x80, 1}, 4, {0, 0, 0, 3, 0, 0x80, 1}, 7, {0, 0, 0, 4, 0, 0, 0x80, 1}, 8},
		{{0x80, 1}, 2, {0, 0, 0, 3, 0, 0x80, 1}, 7, {0, 0, 0, 2, 0x80, 1}, 6},
		{{1, 2}, 2, {0, 0, 0, 2, 1, 2}, 6, {0, 0, 0, 2, 1, 2}, 6},
	};
	unsigned passed = 0;
	for (size_t i = 0; i < sizeof(cases) / sizeof(cases[0]); i++) {
		for (unsigned mode = 0; mode < 2; mode++) {
			uint8_t *out = NULL;
			size_t size = 0;
			const uint8_t *expected = mode == 0 ? cases[i].integer : cases[i].string;
			size_t length = mode == 0 ? cases[i].integer_length : cases[i].string_length;
			int ret = encode_k_wire(cases[i].raw, cases[i].length, mode != 0, &out, &size);
			bool valid = ret == 0 && size == length && memcmp(out, expected, length) == 0;
			if (out != NULL)
				dssh_cleanse(out, size);
			free(out);
			if (valid)
				passed++;
		}
	}
	printf("key encoding: %u/12 byte-exact cases verified\n", passed);
	ASSERT_EQ_U(passed, 12);
	return TEST_PASS;
}

